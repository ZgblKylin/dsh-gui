/**
 * ESM loader generation for remote-tab children.
 *
 * A child `dsh web` is a *separate process*, so its profile plugins import the
 * dsh core packages (`@deepseek-ai/cordis`, `dsh-settings`, `dsh-llm`, …) as
 * bare specifiers. The parent profile does not install those packages: they
 * live in the immutable dsh runtime the host process itself is running from,
 * and the host resolves them through a runtime interception the CLI child does
 * not have. Without help the core imports fail with `ERR_MODULE_NOT_FOUND`, and
 * every host entry that imported one loses its client bundle too (pet, sidebar,
 * usage, settings cards disappear).
 *
 * This module writes one ESM loader into the child home and the supervisor
 * passes it as `--experimental-loader`. For `@deepseek-ai/*` specifiers the
 * loader asks Node to resolve from two anchors in order:
 *
 * 1. the hosting process's runtime anchor — the same installation the parent
 *    runs, so the child shares the host's module instances instead of carrying
 *    a second copy of the framework;
 * 2. the parent profile anchor — plugin packages installed only in the profile
 *    (`dsh-browser-use`, `dsh-computer-use`, …) still resolve.
 *
 * The loader is deliberately generic: it names no backend plugin, only the dsh
 * package scope, and the fallback for every other specifier is Node's normal
 * resolution.
 */

import { mkdirSync, renameSync, rmSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'

/** File name of the generated loader inside the child home. */
export const LOADER_FILE_NAME = 'remote-tab-loader.mjs'

/** Package scope the loader remaps onto the runtime and profile anchors. */
export const LOADER_SCOPE_PREFIX = '@deepseek-ai/'

/** Where the generated loader lives inside one child home. */
export function remoteTabLoaderPath(childHome: string): string {
  return join(childHome, LOADER_FILE_NAME)
}

/** The two resolution anchors of one generated loader. */
export interface RemoteTabLoaderAnchors {
  /** Absolute `package.json` of the hosting dsh runtime; omitted when unknown. */
  readonly runtimeAnchor?: string
  /** Absolute `package.json` of the parent profile. */
  readonly profileAnchor: string
}

/** One generated loader. */
export interface RemoteTabLoader {
  readonly path: string
  readonly source: string
}

/**
 * Write (or refresh) the child loader.
 * @param args - child home plus the two anchors.
 * @returns the loader path and its source.
 */
export function writeRemoteTabLoader(args: { readonly childHome: string } & RemoteTabLoaderAnchors): RemoteTabLoader {
  const path = remoteTabLoaderPath(args.childHome)
  const source = loaderSource(args)
  mkdirSync(dirname(path), { recursive: true })
  const temporary = `${path}.${process.pid}.tmp`
  try {
    writeFileSync(temporary, source, 'utf8')
    renameSync(temporary, path)
  } catch (error: unknown) {
    try {
      rmSync(temporary, { force: true })
    } catch {
      // Best-effort cleanup; the original error is the report.
    }
    throw error
  }
  return { path, source }
}

/**
 * Build the loader source for one pair of anchors.
 *
 * Anchor paths are embedded as JSON strings and converted with `pathToFileURL`
 * inside the loader, so Windows separators and non-ASCII home paths survive.
 * @param anchors - runtime anchor first, parent profile anchor second.
 * @returns the loader module source.
 */
export function loaderSource(anchors: RemoteTabLoaderAnchors): string {
  const runtime = anchors.runtimeAnchor === undefined ? null : anchors.runtimeAnchor
  return `// Generated by dsh-desktop-tabs for one remote-tab child process.
// Resolve the dsh package scope from the hosting runtime first (shared framework
// instances with the parent), then the parent profile (profile-only plugins).
import { pathToFileURL } from 'node:url'

const SCOPE = ${JSON.stringify(LOADER_SCOPE_PREFIX)}
const RUNTIME_ANCHOR_PATH = ${JSON.stringify(runtime)}
const RUNTIME_ANCHOR = RUNTIME_ANCHOR_PATH === null ? null : pathToFileURL(RUNTIME_ANCHOR_PATH).href
const PROFILE_ANCHOR = pathToFileURL(${JSON.stringify(anchors.profileAnchor)}).href
const ANCHORS = RUNTIME_ANCHOR === null ? [PROFILE_ANCHOR] : [RUNTIME_ANCHOR, PROFILE_ANCHOR]

export async function resolve(specifier, context, nextResolve) {
  if (specifier.startsWith(SCOPE)) {
    for (const anchor of ANCHORS) {
      try {
        return await nextResolve(specifier, { ...context, parentURL: anchor })
      } catch {
        // Not provided by that anchor (for example a profile-only plugin when the
        // runtime is asked first, or the reverse); try the next anchor.
      }
    }
  }
  return nextResolve(specifier, context)
}
`
}
